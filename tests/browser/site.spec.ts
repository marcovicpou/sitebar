import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { resolve } from 'node:path';
import AxeBuilder from '@axe-core/playwright';

async function accessible(page:import('@playwright/test').Page) {
  const result=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  expect(result.violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)}))).toEqual([]);
}

test('public navigation, menu filters, gallery and contact work', async ({page})=>{
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.emulateMedia({reducedMotion:'reduce'});
  await accessible(page);
  await expect(page.getByRole('heading',{level:1})).toContainText('Seu ponto de encontro');
  await expect(page.locator('.hero-photo img')).toBeVisible();
  await page.getByRole('navigation',{name:'Navegação principal'}).getByRole('link',{name:'Cardápio',exact:true}).click();
  await expect(page.getByRole('heading',{name:'O que vai ser hoje?'})).toBeVisible();
  await page.getByRole('button',{name:'Bebidas',exact:true}).click();
  await expect(page.locator('.menu-card')).toHaveCount(1);
  await expect(page.locator('.menu-card')).toContainText('Drink Encontro');
  await page.getByLabel('Buscar no cardápio').fill('inexistente');
  await expect(page.getByText('Nada por aqui ainda.')).toBeVisible();
  await page.goto('/galeria.php');
  await page.getByRole('button',{name:'Ampliar foto: Decoração do bar'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button',{name:'Próxima foto'}).click();
  await expect(page.getByRole('dialog')).toHaveAccessibleName('Decoração Pitú');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('button',{name:'Ampliar foto: Decoração do bar'})).toBeFocused();
  await page.goto('/contato.php');
  await page.getByLabel('Seu nome').fill('Amigo do bar');
  await page.getByLabel('Sua mensagem').fill('Gostaria de saber mais sobre a casa.');
  await page.getByRole('button',{name:'Preparar mensagem'}).click();
  await expect(page.getByRole('status')).toContainText('Sua mensagem está pronta');
  const link=await page.getByRole('link',{name:'Abrir no WhatsApp'}).getAttribute('href');
  expect(decodeURIComponent(link!)).toContain('Amigo do bar');
  expect(decodeURIComponent(link!)).toContain('Gostaria de saber mais');
  expect(errors).toEqual([]);
});

test('mobile pages fit 320px and navigation works',async({page})=>{
  await page.setViewportSize({width:320,height:800});
  for(const path of ['/','/cardapio.php','/eventos.php','/galeria.php','/sobre.php','/contato.php']){
    await page.goto(path);
    await expect(page.getByRole('heading',{level:1})).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await page.goto('/');
  await page.getByRole('button',{name:'Abrir menu'}).click();
  await expect(page.getByRole('navigation',{name:'Menu móvel'})).toBeVisible();
  await page.getByRole('navigation',{name:'Menu móvel'}).getByRole('link',{name:'Cardápio'}).click();
  await expect(page.getByRole('heading',{name:'O que vai ser hoje?'})).toBeVisible();
});

test('administrator setup, CRUD, uploads, publication and login work',async({page})=>{
  const password='Test-' + randomUUID();
  const title='Porção criada no teste';
  await page.goto('/admin/');
  await accessible(page);
  await expect(page.getByRole('heading',{name:'Vamos preparar a casa?'})).toBeVisible();
  await page.getByLabel('Usuário',{exact:true}).fill('browser-test');
  await page.getByLabel('Senha',{exact:true}).fill(password);
  await page.getByLabel('Confirmar senha',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Criar meu acesso'}).click();
  await expect(page.getByRole('heading',{name:'Olá, browser-test.'})).toBeVisible();
  await accessible(page);
  await page.getByRole('button',{name:'Cardápio',exact:true}).click();
  await page.getByRole('button',{name:'Adicionar item'}).first().click();
  let dialog=page.getByRole('dialog');
  await dialog.getByLabel('Nome do item').fill(title);
  await dialog.getByLabel('Categoria',{exact:true}).fill('Porções');
  await dialog.getByLabel('Preço (R$)').fill('35,90');
  await dialog.getByLabel('Descrição',{exact:true}).fill('Uma porção adicionada pelo painel.');
  await dialog.getByRole('button',{name:'Salvar alterações'}).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('row').filter({hasText:title})).toContainText('R$');
  const publicPage=await page.context().newPage();
  await publicPage.goto('/cardapio.php');
  await expect(publicPage.locator('.menu-card').filter({hasText:title})).toHaveCount(1);
  await page.getByRole('button',{name:'Ocultar '+title,exact:true}).click();
  await expect(page.getByRole('button',{name:'Publicar '+title,exact:true})).toBeVisible();
  await publicPage.reload();
  await expect(publicPage.locator('.menu-card').filter({hasText:title})).toHaveCount(0);
  await page.getByRole('button',{name:'Editar '+title,exact:true}).click();
  dialog=page.getByRole('dialog');
  await dialog.getByLabel('Nome do item').fill('Porção editada no teste');
  await dialog.getByRole('button',{name:'Salvar alterações'}).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button',{name:'Excluir Porção editada no teste',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Sim, excluir'}).click();
  await expect(page.getByRole('row').filter({hasText:'Porção editada no teste'})).toHaveCount(0);
  await page.getByRole('button',{name:'Agenda de eventos',exact:true}).click();
  await page.getByRole('button',{name:'Adicionar evento'}).first().click();
  dialog=page.getByRole('dialog');
  await dialog.getByLabel('Título',{exact:true}).fill('Encontro criado no teste');
  await dialog.getByLabel('Data',{exact:true}).fill('2026-12-12');
  await dialog.getByLabel('Horário',{exact:true}).fill('20:00');
  await dialog.getByRole('button',{name:'Salvar alterações'}).click();
  await expect(dialog).not.toBeVisible();
  await publicPage.goto('/eventos.php');
  await publicPage.getByRole('link',{name:'Encontro criado no teste',exact:true}).click();
  await expect(publicPage.getByRole('heading',{level:1})).toHaveText('Encontro criado no teste');
  await page.getByRole('button',{name:'Galeria de fotos',exact:true}).click();
  await page.getByRole('button',{name:'Adicionar foto'}).first().click();
  dialog=page.getByRole('dialog');
  await dialog.getByLabel('Título',{exact:true}).fill('Foto enviada no teste');
  await dialog.locator('input[type=file]').setInputFiles({name:'bad.jpg',mimeType:'image/jpeg',buffer:Buffer.from('Not an image')});
  await dialog.getByRole('button',{name:'Salvar alterações'}).click();
  await expect(dialog.getByRole('alert')).toContainText('JPG, PNG ou WEBP válida');
  await dialog.locator('input[type=file]').setInputFiles(resolve('assets/uploads/bar-arte-parede.jpeg'));
  await dialog.getByRole('button',{name:'Salvar alterações'}).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('row').filter({hasText:'Foto enviada no teste'})).toHaveCount(1);
  await publicPage.goto('/galeria.php');
  await publicPage.getByRole('button',{name:'Ampliar foto: Foto enviada no teste'}).click();
  await expect(publicPage.getByRole('dialog')).toBeVisible();
  expect(await publicPage.locator('.lightbox-image').evaluate((img:HTMLImageElement)=>img.complete && img.naturalWidth>0)).toBe(true);
  await page.getByRole('button',{name:'Informações do site',exact:true}).click();
  await page.getByLabel('Descrição do destaque').fill('Um novo texto salvo pelo painel.');
  await page.getByRole('button',{name:'Salvar informações'}).click();
  await expect(page.getByRole('status')).toContainText('Informações do site atualizadas');
  await publicPage.goto('/');
  await expect(publicPage.locator('.hero-description')).toHaveText('Um novo texto salvo pelo painel.');
  await publicPage.close();
  await page.getByRole('button',{name:'Sair do painel'}).click();
  await expect(page.getByRole('heading',{name:'Bom te ver por aqui.'})).toBeVisible();
  await page.getByLabel('Usuário',{exact:true}).fill('browser-test');
  await page.getByLabel('Senha',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Entrar no painel'}).click();
  await expect(page.getByRole('heading',{name:'Olá, browser-test.'})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Abrir navegação'}).click();
  await page.getByRole('button',{name:'Acesso e segurança',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Acesso e segurança',exact:true})).toBeVisible();
});
